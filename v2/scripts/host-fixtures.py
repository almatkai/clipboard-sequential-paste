#!/usr/bin/env python3
import pathlib,subprocess,tempfile,shutil,sys
root=pathlib.Path(__file__).resolve().parents[1]
qa=root/'.qa';qa.mkdir(exist_ok=True)
out=pathlib.Path(tempfile.mkdtemp(prefix='host-fixtures-',dir=qa))
shutil.copytree(root/'fixtures/host',out,dirs_exist_ok=True)
for patch in sorted((root/'host-patches').glob('*.patch')):
 subprocess.run(['patch','--dry-run','--batch','--fuzz=0','-p1','-i',str(patch)],check=True,cwd=out,stdout=subprocess.DEVNULL)
 subprocess.run(['patch','--batch','--fuzz=0','-p1','-i',str(patch)],check=True,cwd=out,stdout=subprocess.DEVNULL)
# Extract real function bodies, not hand rewritten mirrors. Exact closure scanner
# uses the next top-level item; these frozen functions have no nested top-level items.
def fn(text,name):
 start=text.index('fn '+name)
 start=text.rfind('\n',0,start)+1
 end=text.find('\n}',start)+2
 return text[start:end]+'\n'
registry='src-tauri/src/native_core/extensions/registry.rs'
original=(root/'fixtures/host'/registry).read_text();patched=(out/registry).read_text()
parts=['// Generated exact function extraction by scripts/host-fixtures.py.\n']
for name in ['fallback','compatible','icon_path']:
 parts.append(fn(original,name).replace('fn '+name,'pub fn original_'+name) if name=='icon_path' else fn(original,name))
parts.append(fn(patched,'icon_path').replace('fn icon_path','pub fn patched_icon_path'))
parts.append(fn(patched,'verified_replacement').replace('pub(super) fn','pub fn'))
parts.append(fn((root/'fixtures/host/src-tauri/src/native_core/extensions/process_host.rs').read_text(),'string').replace('fn string','pub fn typed_string'))
parts.append(fn((root/'fixtures/host/src-tauri/src/native_core/launcher/stores.rs').read_text(),'text_arg'))
# All Installed constructors in the patched fixture carry the new asset root.
assert patched.count('Installed {')==patched.count('package_dir,')+patched.count('package_dir: None,')+1
text='\n'.join(parts)
dest=root/'fixtures/host-functions.rs'
if '--check' in sys.argv: assert dest.read_text()==text
else:dest.write_text(text)
native='src-tauri/src/native_core/extensions/native.rs'
old_native=(root/'fixtures/host'/native).read_text();new_native=(out/native).read_text()
def method(text,name):
 start=text.index('    async fn '+name) if name=='dispatch' else text.index('    fn '+name)
 end=text.index('\n    }',start)+6
 return text[start:end]+'\n'
extra='// Exact frozen/patched host methods, generated by scripts/host-fixtures.py.\n'
for mod,text in [('original_dispatch',old_native),('patched_dispatch',new_native)]:
 extra+='mod '+mod+' {\nuse super::*;\nstruct NativeSessions(Arc<Mutex<State>>);\nimpl NativeSessions {\n'+method(text,'remove')+method(text,'dispatch')+'}\n'+fn(text,'deadline')+fn(text,'annotate')+'\npub async fn run(s: &super::NativeSessions, channel: &str) -> CoreResult { let s = NativeSessions(s.0.clone()); s.dispatch(channel, &json!({}), "s").await }\n}\n'
dest=root/'fixtures/host-lifecycle-functions.rs'
if '--check' in sys.argv: assert dest.read_text()==extra
else:dest.write_text(extra)
(root/'.qa/patched-host-path').write_text(str(out))
print('4 UNAPPLIED host patches apply cleanly to frozen fixtures; exact extracted functions verified')
